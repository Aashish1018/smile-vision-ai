"""Treatment catalog and clinic price sheets, loaded from `knowledge/catalog.yaml`.

Costs are looked up here, never generated by a model.
"""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path

import yaml
from pydantic import BaseModel

from smileos.vision.schemas import Category


class Treatment(BaseModel):
    code: str
    name: str
    addresses: list[Category]
    unit: str
    kb: str
    duration: str
    requires_exam: bool = False


class Clinic(BaseModel):
    slug: str
    name: str
    currency: str
    prices: dict[str, tuple[int, int]]


class CostLine(BaseModel):
    code: str
    name: str
    quantity: int
    unit: str
    low: int
    high: int


class CostEstimate(BaseModel):
    clinic: str
    currency: str
    lines: list[CostLine]
    total_low: int
    total_high: int
    note: str = "Indicative range for planning only. The clinic confirms the final price after examination."


class Catalog(BaseModel):
    treatments: dict[str, Treatment]
    clinics: dict[str, Clinic]

    def for_categories(self, categories: set[Category]) -> list[Treatment]:
        return [t for t in self.treatments.values() if categories & set(t.addresses)]

    def estimate(self, clinic_slug: str, items: list[tuple[str, int]]) -> CostEstimate:
        clinic = self.clinics[clinic_slug]
        lines = []
        for code, qty in items:
            if code not in clinic.prices:
                continue
            low, high = clinic.prices[code]
            t = self.treatments[code]
            lines.append(CostLine(code=code, name=t.name, quantity=qty, unit=t.unit, low=low * qty, high=high * qty))
        return CostEstimate(
            clinic=clinic.name,
            currency=clinic.currency,
            lines=lines,
            total_low=sum(line.low for line in lines),
            total_high=sum(line.high for line in lines),
        )


def load_catalog(path: Path) -> Catalog:
    raw = yaml.safe_load(path.read_text())
    return Catalog(
        treatments={code: Treatment(code=code, **spec) for code, spec in raw["treatments"].items()},
        clinics={c["slug"]: Clinic(**c) for c in raw["clinics"]},
    )


@lru_cache
def default_catalog() -> Catalog:
    from smileos.core.config import get_settings

    return load_catalog(get_settings().knowledge_dir / "catalog.yaml")
